/* Mechanical crop/alpha cleanup only; no smoothing or bilinear resizing.
   Source sheets are reference-derived, not claimed to be the user's originals.
   Uses Sharp when available in the development environment; no runtime package. */
const fs = require('fs'), path = require('path'), sharp = require('sharp');
const root = path.join(__dirname, '..');
const sources = 'art-src/world/';
const assets = {};
const entries = [
  ['pine','vegetation','vegetation-sheet.png',[70,220,285,330]],
  ['pine-tall','vegetation','vegetation-sheet.png',[375,140,310,410]],
  ['oak','vegetation','vegetation-sheet.png',[695,170,355,380]],
  ['cherry','vegetation','vegetation-sheet.png',[1045,170,370,380]],
  ['crimson','vegetation','vegetation-sheet.png',[1430,180,345,360]],
  ['bush','vegetation','vegetation-sheet.png',[1785,300,340,250]],
  ['flowers','props','props-sheet.png',[0,225,355,300]],
  ['rocks','props','props-sheet.png',[365,220,335,300]],
  ['bridge','props','props-sheet.png',[700,200,400,330]],
  ['dock','props','props-sheet.png',[1100,230,430,300]],
  ['boat','water','props-sheet.png',[1530,180,355,360]],
  ['grass','props','props-sheet.png',[1880,250,290,280]],
  ['capitol','landmarks','landmarks-sheet.png',[70,100,600,530]],
  ['monument','landmarks','landmarks-sheet.png',[750,90,230,540]],
  ['jefferson','landmarks','landmarks-sheet.png',[1055,170,570,450]],
  ['liberty','landmarks','landmarks-sheet.png',[1740,70,370,560]],
  ['grass-light','ground','pack-reference-derived.png',[35,45,64,64]],
  ['grass-medium','ground','pack-reference-derived.png',[172,44,64,64]],
  ['forest-floor','ground','pack-reference-derived.png',[294,44,64,64]],
  ['dirt','ground','pack-reference-derived.png',[673,44,60,60]],
  ['sand','ground','pack-reference-derived.png',[788,42,60,60]],
  ['water-shallow','ground','pack-reference-derived.png',[1240,45,48,48]],
  ['water-deep','ground','pack-reference-derived.png',[1335,45,60,60]]
];
async function prepare() {
  for (const [name,category,source,box] of entries) {
    const [left,top,width,height]=box;
    let pipeline=sharp(path.join(root,sources,source)).extract({left,top,width,height}).ensureAlpha();
    if(category!=='ground'){
      const {data,info}=await pipeline.raw().toBuffer({resolveWithObject:true});
      for(let i=0;i<data.length;i+=4){
        // Remove exact chroma-key contamination, not legitimate pink blossoms.
        if((data[i]>240&&data[i+1]<20&&data[i+2]>235)||data[i+3]<40)data[i+3]=0;
      }
      pipeline=sharp(data,{raw:info}).trim({background:'#00000000',threshold:2}).resize({width:128,height:128,fit:'inside',kernel:'nearest'});
    }
    const file='art/world/'+category+'/'+name+'.png';
    fs.mkdirSync(path.dirname(path.join(root,file)),{recursive:true});
    await pipeline.png({compressionLevel:9}).toFile(path.join(root,file));
    const meta=await sharp(path.join(root,file)).metadata();
    assets['pack-'+name]={path:file,width:meta.width,height:meta.height,anchor:category==='ground'?[0,0]:[.5,1],category,
      use:category==='ground'?'low-contrast seamless region texture':'world-coordinate decoration',source:sources+source,crop:box};
  }
  for(const id of ['nyc-area','nyc-waterfront','dc-area']){
    const source=sources+id+'-clean.png',file='art/world/regions/'+id+'.webp';
    fs.mkdirSync(path.dirname(path.join(root,file)),{recursive:true});
    await sharp(path.join(root,source)).webp({lossless:true,effort:6}).toFile(path.join(root,file));
    const m=await sharp(path.join(root,file)).metadata();
    assets[id]={path:file,width:m.width,height:m.height,anchor:[.5,.5],category:'region',use:'clean authored scene; independent geographic markers',source};
  }
  const manifest={version:1,provenance:'Reference-derived clean art; original chat uploads are not present as source PNGs.',rendering:'nearest-neighbor',assets};
  fs.mkdirSync(path.join(root,'src/world/data'),{recursive:true});
  fs.writeFileSync(path.join(root,'src/world/data/asset-manifest.json'),JSON.stringify(manifest,null,2)+'\n');
  fs.writeFileSync(path.join(root,'src/world/assets.generated.js'),'/* Generated by tools/prepare-world-assets.js */\nvar WORLD_ASSETS = '+JSON.stringify(assets)+';\n');
  console.log('Prepared '+Object.keys(assets).length+' verified assets.');
}
prepare().catch(e=>{console.error(e);process.exit(1);});
