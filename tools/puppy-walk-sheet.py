#!/usr/bin/env python3
"""Cut the 4 x 6 side-walking sheet (art-src/pets/puppy-walk-sheet.png) into art/pets/puppy-walk.webp
and register it in tools/puppy-anims.json / src/features/pet-anims.js. The frames face right; the room flips them to walk left."""
import os, sys, json
from PIL import Image
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from puppy_cut import cut as cut_bg
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
ROWS = [(105, 330), (395, 615), (660, 890), (940, 1170)]
X0, DX, W = 15, 205, 211
SCALE, CH = 0.98, 256
GROUND = CH - round(0.055 * CH)

im = Image.open(os.path.join(ROOT, 'art-src', 'pets', 'puppy-walk-sheet.png')).convert('RGB')
frames = [cut_bg(im.crop((X0 + DX * i, ROWS[r][0], X0 + DX * i + W, ROWS[r][1])), min_gap=60) for r in range(4) for i in range(6)]
cw = round(W * SCALE) + 8; cw += cw % 2
cols = 8; rows = 3
sheet = Image.new('RGBA', (cw * cols, CH * rows), (0, 0, 0, 0))
for i, f in enumerate(frames):
    bb = f.getchannel('A').point(lambda v: 255 if v > 90 else 0).getbbox()
    s = f.resize((round(f.width * SCALE), round(f.height * SCALE)), Image.LANCZOS)
    cell = Image.new('RGBA', (cw, CH), (0, 0, 0, 0))
    cell.alpha_composite(s, (4, GROUND - round(bb[3] * SCALE)))
    sheet.alpha_composite(cell, ((i % cols) * cw, (i // cols) * CH))
out = os.path.join(ROOT, 'art', 'pets', 'puppy-walk.webp')
sheet.save(out, quality=72, method=6, alpha_quality=80)
reg = os.path.join(ROOT, 'tools', 'puppy-anims.json')
anims = json.load(open(reg)); anims['walk'] = {'cw': cw, 'ch': CH, 'cols': cols, 'rows': rows, 'n': 24, 'fps': 14}
json.dump(anims, open(reg, 'w'), indent=1, sort_keys=True)
open(os.path.join(ROOT, 'src', 'features', 'pet-anims.js'), 'w', encoding='utf8').write(
    '/* Generated by tools/puppy-sheets.py: the puppy animation sheets (art/pets/puppy-<name>.webp). Do not edit by hand. */\nvar PUP_ANIMS = ' + json.dumps(anims, sort_keys=True) + ';\n')
print(cw, CH, os.path.getsize(out) // 1024, 'KB')
